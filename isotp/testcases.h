/* print the CAN XL SDT (if any) and the N_PDU type, e.g. 'CC' or '9FD' */
static inline void print_tcd_type(const struct isotp_testcase_description *t)
{
	const char *npdu = "CC";

	if (t->mtu == CANFD_MTU)
		npdu = "FD";
	else if (t->mtu == CANXL_MTU)
		npdu = "XL";

	if (t->sdt)
		printf("%X", t->sdt);

	printf("%s", npdu);
}

